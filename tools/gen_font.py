HERE = os.path.dirname(os.path.abspath(__file__))
DST = os.path.normpath(os.path.join(HERE, "..", "port", "hsv3_font.c"))


def render(text: str) -> None:
    """Desenha texto em ASCII, exatamente como o OLED o mostraria."""
    rows = []
    for r in range(7):
        line = ""
        for ch in text:
            cols = FONT[ord(ch) - 32]
            for c in cols:
                line += "#" if (c >> r) & 1 else "."
            line += "."
        rows.append(line)
    print("\n".join(rows))


def main() -> int:
    if len(FONT) != 95:
        print(f"ERRO: {len(FONT)} glifos, esperados 95 (ASCII 32..126)", file=sys.stderr)
        return 1
    for i, g in enumerate(FONT):
        if len(g) != 5:
            print(f"ERRO: glifo {i} ({chr(32+i)!r}) tem {len(g)} colunas", file=sys.stderr)
            return 1
        if any(b > 0x7F for b in g):
            print(f"ERRO: glifo {i} ({chr(32+i)!r}) usa o bit 7", file=sys.stderr)
            return 1

    if "--render" in sys.argv:
        for sample in ("abandon zoo", "0123456789", "Fingerprint:", "bc1q 84'/0'"):
            print(f"--- {sample!r} ---")
            render(sample)
            print()
        return 0

    lines = [
        "/* GERADO POR tools/gen_font.py -- NAO EDITAR A MAO.",
        " *",
        " * Fonte 5x7, ASCII 32..126. Cada caractere sao 5 colunas; em cada byte",
        " * o bit 0 e' a linha de cima. Confere os glifos com:",
        " *     python tools/gen_font.py --render",
        " */",
        '#include "hsv3_font.h"',
        "",
        "const uint8_t hsv3_font5x7[HSV3_FONT_CHARS][HSV3_FONT_WIDTH] = {",
    ]
    for i, g in enumerate(FONT):
        ch = chr(32 + i)
        label = "espaco" if ch == " " else ch
        cols = ", ".join(f"0x{b:02X}" for b in g)
        lines.append(f"    {{ {cols} }},   /* {32+i:3d}  {label} */")
    lines += ["};", ""]

    with open(DST, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"escrito {os.path.relpath(DST, os.path.join(HERE, '..'))}")
    print(f"95 glifos, {95 * 5} bytes em flash")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
